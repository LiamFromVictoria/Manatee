const primary = "blue"

// variantSuffixes are the per-color semantic vars consumed by components via --mt-c-*.
var variantSuffixes = []string{"filled", "filled-hover", "light", "light-hover", "light-color", "outline", "outline-hover", "text"}

func shade(name string, i int) string { return fmt.Sprintf("var(--mt-color-%s-%d)", name, i) }

func rgba(hex string, alpha float64) string {
	h := strings.TrimPrefix(hex, "#")
	r, _ := strconv.ParseUint(h[0:2], 16, 8)
	g, _ := strconv.ParseUint(h[2:4], 16, 8)
	b, _ := strconv.ParseUint(h[4:6], 16, 8)
	return fmt.Sprintf("rgba(%d, %d, %d, %g)", r, g, b, alpha)
}

