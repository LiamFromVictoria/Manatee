// Command mticons generates icons/icons_gen.go from the Tabler icon set
// (MIT, https://tabler.io/icons). It downloads the pinned npm tarball
// directly (no Node needed) and emits one templ component per name listed in
// icons/icons.txt. Run via `go generate ./icons`.
package main

import (
	"archive/tar"
	"compress/gzip"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"unicode"
)

const tablerVersion = "3.52.0"

func main() {
	list := flag.String("list", "icons.txt", "icon name list")
	out := flag.String("out", "icons_gen.go", "output Go file")
	flag.Parse()

	names, err := readList(*list)
	if err != nil {
		fatal(err)
	}
	svgs, err := fetch(tablerVersion)
	if err != nil {
		fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cmd/mticons from Tabler Icons v%s (MIT); DO NOT EDIT.\n\npackage icons\n\nimport \"github.com/a-h/templ\"\n\n", tablerVersion)
	var missing []string
	for _, name := range names {
		file, filled := tablerFile(name)
		svg, ok := svgs[file]
		if !ok {
			missing = append(missing, name+" ("+file+")")
			continue
		}
		kind := "outline"
		if filled {
			kind = "filled"
		}
		fmt.Fprintf(&b, "// %s renders the Tabler %q icon (%s).\nfunc %s(p ...Props) templ.Component { return render(p, %t, %q) }\n\n",
			name, strings.TrimSuffix(strings.TrimPrefix(file, kind+"/"), ".svg"), kind, name, filled, body(svg))
	}
	if len(missing) > 0 {
		fatal(fmt.Errorf("not found in Tabler v%s: %s", tablerVersion, strings.Join(missing, ", ")))
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("mticons: %d icons -> %s\n", len(names), *out)
}

func readList(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		names = append(names, line)
	}
	slices.Sort(names)
	return slices.Compact(names), nil
}

// tablerFile maps a React name (IconChartPie3, IconBookmarkFilled) to its
// tarball path (outline/chart-pie-3.svg, filled/bookmark.svg).
func tablerFile(name string) (string, bool) {
	base := strings.TrimPrefix(name, "Icon")
	filled := strings.HasSuffix(base, "Filled")
	base = strings.TrimSuffix(base, "Filled")
	var kebab strings.Builder
	runes := []rune(base)
	for i, r := range runes {
		if i > 0 && (unicode.IsUpper(r) || (unicode.IsDigit(r) && unicode.IsLetter(runes[i-1]))) {
			kebab.WriteByte('-')
		}
		kebab.WriteRune(unicode.ToLower(r))
	}
	dir := "outline"
	if filled {
		dir = "filled"
	}
	return dir + "/" + kebab.String() + ".svg", filled
}

var (
	svgInner    = regexp.MustCompile(`(?s)<svg[^>]*>(.*)</svg>`)
	boundingBox = regexp.MustCompile(`<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>`)
	whitespace  = regexp.MustCompile(`\s+`)
)

func body(svg string) string {
	m := svgInner.FindStringSubmatch(svg)
	if m == nil {
		return ""
	}
	inner := boundingBox.ReplaceAllString(m[1], "")
	return strings.TrimSpace(whitespace.ReplaceAllString(inner, " "))
}

func fetch(version string) (map[string]string, error) {
	url := "https://registry.npmjs.org/@tabler/icons/-/icons-" + version + ".tgz"
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	gz, err := gzip.NewReader(resp.Body)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return out, nil
		}
		if err != nil {
			return nil, err
		}
		rel, ok := strings.CutPrefix(h.Name, "package/icons/")
		if !ok || !strings.HasSuffix(rel, ".svg") {
			continue
		}
		data, err := io.ReadAll(tr)
		if err != nil {
			return nil, err
		}
		out[rel] = string(data)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "mticons:", err)
	os.Exit(1)
}
